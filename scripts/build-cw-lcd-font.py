UNITS = 64
ROWS = (2, 2, 1, 2, 1, 2, 2, 2)
COLS = (2, 1, 2, 1, 2)


def outline(char, pattern):
    pen = TTGlyphPen(None)
    rows = pattern.split("/")
    columns = COLS if len(rows[0]) == 5 else (1,) * len(rows[0])
    width = sum(columns)
    advance = 11 if char.isdigit() else width + 2
    left = (advance - width) * UNITS // 2
    top = 12 * UNITS
    for row, height in zip(rows, ROWS):
        x = left
        bottom = top - height * UNITS
        for cell, dots in zip(row, columns):
            right = x + dots * UNITS
            if cell == "1":
                pen.moveTo((x, bottom))
                pen.lineTo((x, top))
                pen.lineTo((right, top))
                pen.lineTo((right, bottom))
                pen.closePath()
            x = right
        top = bottom
    glyph = pen.glyph()
    return glyph, (advance * UNITS, glyph.xMin if hasattr(glyph, "xMin") else left)


def build(destination):
    glyphs = {".notdef": TTGlyphPen(None).glyph(), "space": TTGlyphPen(None).glyph()}
    metrics = {".notdef": (0, 0), "space": (5 * UNITS, 0)}
    cmap = {32: "space", 0xA0: "space"}
    for char, pattern in GLYPHS.items():
        name = f"uni{ord(char):04X}"
        glyphs[name], metrics[name] = outline(char, pattern)
        cmap[ord(char)] = name
        # The linear editor distinguishes engineering suffixes with full-width
        # letters. Their visible glyphs match the corresponding Latin symbols.
        if char in "mnpfkMGTPE":
            cmap[ord(char) + 0xFEE0] = name

    font = FontBuilder(1024, isTTF=True)
    font.setupGlyphOrder(list(glyphs))
    font.setupCharacterMap(cmap)
    font.setupGlyf(glyphs)
    for name, glyph in glyphs.items():
        metrics[name] = (metrics[name][0], getattr(glyph, "xMin", 0))
    font.setupHorizontalMetrics(metrics)
    font.setupHorizontalHeader(ascent=13 * UNITS, descent=-3 * UNITS, lineGap=0)
    font.setupNameTable({
        "familyName": "CNX LCD",
        "styleName": "Regular",
        "uniqueFontIdentifier": "CNX LCD Regular 1.0",
        "fullName": "CNX LCD Regular",
        "psName": "CNXLCD-Regular",
        "version": "Version 1.0",
    })
    font.setupOS2(version=4, sTypoAscender=13 * UNITS, sTypoDescender=-3 * UNITS,
                  sTypoLineGap=0, usWinAscent=13 * UNITS, usWinDescent=3 * UNITS,
                  fsSelection=0xC0)
    font.setupPost()
    font.font.recalcTimestamp = False
    font.font["head"].created = font.font["head"].modified = 3786912000
    font.font.flavor = "woff"
    destination.parent.mkdir(parents=True, exist_ok=True)
    font.save(destination)


